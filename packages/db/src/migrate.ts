import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import pg from 'pg';

/** Arbitrary constant identifying the testRex migration lock. */
const MIGRATION_LOCK_ID = 4_247_110_991;
const MIGRATIONS_TABLE = '_testrex_migrations';
const STATEMENT_BREAKPOINT = '--> statement-breakpoint';

export interface Migration {
  tag: string;
  hash: string;
  statements: string[];
}

export interface MigrationStatus {
  expected: number;
  applied: number;
  pending: string[];
}

export class MigrationError extends Error {
  constructor(
    readonly migration: string,
    cause: unknown,
  ) {
    super(
      `Migration ${migration} failed: ${cause instanceof Error ? cause.message : String(cause)}`,
      {
        cause,
      },
    );
    this.name = 'MigrationError';
  }
}

interface Journal {
  entries: { idx: number; tag: string }[];
}

/** Reads migrations generated by drizzle-kit, in journal order. */
export function readMigrations(dir: string): Migration[] {
  const journal = JSON.parse(readFileSync(join(dir, 'meta', '_journal.json'), 'utf8')) as Journal;
  return [...journal.entries]
    .sort((a, b) => a.idx - b.idx)
    .map(({ tag }) => {
      const sql = readFileSync(join(dir, `${tag}.sql`), 'utf8');
      const statements = sql
        .split(STATEMENT_BREAKPOINT)
        .map((statement) => statement.trim())
        .filter((statement) => stripSqlComments(statement).length > 0);
      return { tag, hash: createHash('sha256').update(sql).digest('hex'), statements };
    });
}

function stripSqlComments(sql: string): string {
  return sql.replace(/--.*$/gm, '').trim();
}

/**
 * Finds the migrations directory: MIGRATIONS_DIR, next to a bundled app (dist/../migrations),
 * or the source tree when running from the monorepo.
 */
export function resolveMigrationsDir(fromDir: string): string {
  const candidates = [
    process.env.MIGRATIONS_DIR,
    resolve(fromDir, '../migrations'),
    resolve(fromDir, '../../../packages/db/migrations'),
    resolve(import.meta.dirname, '../migrations'),
  ].filter((dir): dir is string => Boolean(dir));
  const found = candidates.find((dir) => existsSync(join(dir, 'meta', '_journal.json')));
  if (!found)
    throw new Error(`Migrations directory not found (looked in ${candidates.join(', ')})`);
  return found;
}

export interface MigrateOptions {
  connectionString: string;
  migrationsDir: string;
  onApplied?: (tag: string) => void;
}

/**
 * Applies pending migrations, each in its own transaction. A Postgres advisory lock ensures
 * concurrent instances apply every migration exactly once.
 */
export async function migrate(options: MigrateOptions): Promise<{ applied: string[] }> {
  const migrations = readMigrations(options.migrationsDir);
  const client = new pg.Client({ connectionString: options.connectionString });
  await client.connect();
  try {
    await client.query('SELECT pg_advisory_lock($1)', [MIGRATION_LOCK_ID]);
    try {
      await client.query(
        `CREATE TABLE IF NOT EXISTS ${MIGRATIONS_TABLE} (
           tag text PRIMARY KEY,
           hash text NOT NULL,
           applied_at timestamptz NOT NULL DEFAULT now()
         )`,
      );
      // Runtime roles read this table for readiness checks; it holds nothing sensitive.
      await client.query(`GRANT SELECT ON ${MIGRATIONS_TABLE} TO PUBLIC`);
      const done = await appliedTags(client);
      const applied: string[] = [];
      for (const migration of migrations) {
        if (done.has(migration.tag)) continue;
        await applyMigration(client, migration);
        applied.push(migration.tag);
        options.onApplied?.(migration.tag);
      }
      return { applied };
    } finally {
      await client.query('SELECT pg_advisory_unlock($1)', [MIGRATION_LOCK_ID]);
    }
  } finally {
    await client.end();
  }
}

async function applyMigration(client: pg.Client, migration: Migration): Promise<void> {
  try {
    await client.query('BEGIN');
    for (const statement of migration.statements) await client.query(statement);
    await client.query(`INSERT INTO ${MIGRATIONS_TABLE} (tag, hash) VALUES ($1, $2)`, [
      migration.tag,
      migration.hash,
    ]);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw new MigrationError(migration.tag, error);
  }
}

async function appliedTags(client: pg.ClientBase | pg.Pool): Promise<Set<string>> {
  const table = await client.query<{ exists: boolean }>(
    'SELECT to_regclass($1) IS NOT NULL AS exists',
    [MIGRATIONS_TABLE],
  );
  if (!table.rows[0]?.exists) return new Set();
  const result = await client.query<{ tag: string }>(`SELECT tag FROM ${MIGRATIONS_TABLE}`);
  return new Set(result.rows.map((row) => row.tag));
}

/** Compares the migrations shipped with this build against those applied to the database. */
export async function getMigrationStatus(
  pool: pg.Pool,
  migrationsDir: string,
): Promise<MigrationStatus> {
  const expected = readMigrations(migrationsDir).map((m) => m.tag);
  const done = await appliedTags(pool);
  const pending = expected.filter((tag) => !done.has(tag));
  return { expected: expected.length, applied: expected.length - pending.length, pending };
}
